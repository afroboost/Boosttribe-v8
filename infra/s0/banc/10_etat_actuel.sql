create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text,
  avatar_url text,
  role text default 'user',
  subscription_status text default 'free',
  has_accepted_terms boolean default false,
  terms_accepted boolean default false,
  comp_access_plan text,
  comp_access_until timestamptz,
  coach_payment_type text not null default 'subscription'
    check (coach_payment_type in ('subscription','commission')),   -- infra/coach-subscription/schema.sql:14
  stripe_customer_id text,
  stripe_subscription_id text,
  live_preferences jsonb,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);
alter table public.profiles enable row level security;
create policy "profiles_select" on public.profiles for select using (true);
create policy "profiles_insert" on public.profiles for insert with check (auth.uid() = id);
create policy "profiles_update" on public.profiles for update using (auth.uid() = id);

-- playlists (une ligne par session : le frontend fait upsert onConflict session_id) + règles
-- de frontend/SUPABASE_RLS_SESSION_SHARING.sql ; access_requests + règles de
-- infra/access/session-access-requests.sql.
create table public.playlists (
  id uuid default gen_random_uuid() primary key,
  session_id text unique not null,
  host_id uuid, cohosts text[],
  mode text not null default 'open',                    -- infra/billetterie/schema.sql:14
  price_chf numeric, capacity int, access_mode text,
  is_private boolean not null default false,            -- frontend/SUPABASE_PRIVATE_SESSIONS.sql:11
  tracks jsonb default '[]', selected_track_id text, shared_media jsonb, description text, live_ended_at timestamptz,
  record_enabled boolean not null default false,        -- infra/recording/schema.sql:7
  created_at timestamptz default now(), updated_at timestamptz default now()
);
alter table public.playlists enable row level security;
create policy "playlists_select" on public.playlists for select using (true);
create policy "playlists_insert" on public.playlists for insert to authenticated
  with check (host_id is null or (host_id)::text = (auth.uid())::text);
create policy "playlists_update" on public.playlists for update to authenticated
  using (host_id is null or (host_id)::text = (auth.uid())::text
         or (auth.uid())::text = any (coalesce(cohosts, array[]::text[])))
  with check (host_id is null or (host_id)::text = (auth.uid())::text
         or (auth.uid())::text = any (coalesce(cohosts, array[]::text[])));
create table public.access_requests (
  id bigint generated by default as identity primary key, session_id text not null,
  requester_user_id uuid, requester_name text not null, status text not null default 'pending',
  created_at timestamptz not null default now(), decided_at timestamptz
);
alter table public.access_requests enable row level security;
create policy access_requests_host_select on public.access_requests for select to authenticated
  using (exists (select 1 from public.playlists p where p.session_id = access_requests.session_id and p.host_id = auth.uid())
         or requester_user_id = auth.uid());
create policy access_requests_host_update on public.access_requests for update to authenticated
  using (exists (select 1 from public.playlists p where p.session_id = access_requests.session_id and p.host_id = auth.uid()))
  with check (exists (select 1 from public.playlists p where p.session_id = access_requests.session_id and p.host_id = auth.uid()));

